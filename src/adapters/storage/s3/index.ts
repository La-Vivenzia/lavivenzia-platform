import {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import {
  isStaticAssetKey,
  type SignedUpload,
  type StoragePort,
  type StoredObject,
} from "@/ports/storage";
import { InternalError, ProviderUnavailableError, ValidationError } from "@/lib/errors";

/**
 * S3-compatible object storage, used against Cloudflare R2.
 *
 * The only file in the codebase that knows the storage provider. Everything
 * above depends on `StoragePort`, so moving between R2, S3 or MinIO is a
 * configuration change rather than a code change — all three speak the same
 * API, which is why R2 needs no adapter of its own.
 *
 * **Two R2 specifics are worth knowing**, because they differ from Amazon S3
 * and are easy to get wrong:
 *
 * 1. **Region is always `auto`.** R2 has no regions; the SDK still requires the
 *    field, and a plausible-looking value mismatches the signature.
 * 2. **The public URL is not the API endpoint.** Objects are served from a
 *    bucket's public r2.dev domain or a custom domain, which is a different
 *    host from the S3 endpoint used to write them. Conflating the two produces
 *    URLs that return 401 to every traveller.
 */

/** Signed URLs are short-lived: handed to a browser, never stored. */
const DEFAULT_UPLOAD_EXPIRY_SECONDS = 15 * 60;

export interface S3StorageConfig {
  readonly bucket: string;
  /** S3 API endpoint, e.g. `https://<account>.r2.cloudflarestorage.com`. */
  readonly endpoint: string;
  readonly accessKeyId: string;
  readonly secretAccessKey: string;
  /**
   * Origin objects are publicly served from — an r2.dev domain or a custom
   * one. Distinct from `endpoint`; see the note above.
   */
  readonly publicBaseUrl: string;
  /** R2 ignores region but the SDK requires one. Overridable for real S3. */
  readonly region?: string | undefined;
}

/** The slice of the SDK this adapter uses, so tests need no network. */
export interface S3SendClient {
  send(command: unknown): Promise<unknown>;
}

export interface S3StorageAdapterDeps {
  /** Injected in tests. Built from config in production. */
  readonly client?: S3SendClient;
  /** Injected in tests so signing needs no real credentials. */
  readonly sign?: (client: S3SendClient, command: unknown, expiresIn: number) => Promise<string>;
}

/**
 * Keys are generated by the domain, but this adapter is the last place that
 * can stop a traversal reaching the bucket, so it checks rather than trusts —
 * the same posture the local adapter takes with the filesystem.
 */
function assertSafeKey(key: string): void {
  if (!key || key.startsWith("/") || key.includes("..") || key.includes("\\")) {
    throw new ValidationError("Invalid storage key.", { key });
  }
}

export class S3StorageAdapter implements StoragePort {
  readonly #config: S3StorageConfig;
  readonly #sign: NonNullable<S3StorageAdapterDeps["sign"]>;
  #client: S3SendClient | undefined;

  constructor(config: S3StorageConfig, deps: S3StorageAdapterDeps = {}) {
    if (!config.bucket) throw new InternalError("S3 storage requires S3_MEDIA_BUCKET.");
    if (!config.endpoint) throw new InternalError("S3 storage requires S3_ENDPOINT.");
    if (!config.accessKeyId || !config.secretAccessKey) {
      throw new InternalError("S3 storage requires S3_ACCESS_KEY_ID and S3_SECRET_ACCESS_KEY.");
    }
    if (!config.publicBaseUrl) {
      throw new InternalError("S3 storage requires S3_PUBLIC_BASE_URL.");
    }

    this.#config = config;
    this.#client = deps.client;
    this.#sign =
      deps.sign ??
      ((client, command, expiresIn) =>
        getSignedUrl(client as S3Client, command as never, { expiresIn }));
  }

  /**
   * Built on first use rather than in the constructor, matching the email
   * adapters: process startup stays free of provider construction.
   */
  #getClient(): S3SendClient {
    this.#client ??= new S3Client({
      // R2 has no regions. See the note at the top of this file.
      region: this.#config.region ?? "auto",
      endpoint: this.#config.endpoint,
      credentials: {
        accessKeyId: this.#config.accessKeyId,
        secretAccessKey: this.#config.secretAccessKey,
      },
    });

    return this.#client;
  }

  /**
   * Translate a provider failure onto the shared error model.
   *
   * The distinction downstream is retryable versus terminal, exactly as in the
   * email adapters. A 4xx is our configuration — wrong bucket, bad credential —
   * and must page someone rather than be retried. Anything unrecognised is
   * treated as retryable: an unknown network fault is far more likely transient
   * than permanent.
   */
  #translate(caught: unknown, operation: string, key: string): Error {
    const error = (caught ?? {}) as {
      name?: string;
      $metadata?: { httpStatusCode?: number };
    };
    const name = error.name ?? "UnknownError";
    const httpStatus = error.$metadata?.httpStatusCode;

    // Narrow on purpose: enough to identify the failure, nothing that reveals a
    // credential or the object's contents.
    const context = { provider: "s3", operation, key, providerError: name, httpStatus };

    if (httpStatus !== undefined && httpStatus >= 400 && httpStatus < 500) {
      return new InternalError(`Object storage rejected the request: ${name}`, context, {
        cause: caught,
      });
    }

    return new ProviderUnavailableError("Object storage is unavailable.", context, {
      cause: caught,
    });
  }

  /**
   * A presigned PUT.
   *
   * `fields` is empty by design: this is a presigned URL rather than a POST
   * policy, so the browser sends bytes with `PUT` and no form fields. The shape
   * is kept because `StoragePort` promises it and a POST-policy provider would
   * fill it.
   *
   * `maxBytes` is **not** enforced by the signature — a presigned PUT cannot
   * carry a size condition. The limit is enforced before this is reached, in
   * the media domain, which checks the declared size and then the actual bytes.
   */
  async createSignedUpload(input: {
    readonly key: string;
    readonly contentType: string;
    readonly maxBytes: number;
  }): Promise<SignedUpload> {
    assertSafeKey(input.key);

    const command = new PutObjectCommand({
      Bucket: this.#config.bucket,
      Key: input.key,
      ContentType: input.contentType,
    });

    try {
      const url = await this.#sign(this.#getClient(), command, DEFAULT_UPLOAD_EXPIRY_SECONDS);

      return {
        url,
        fields: {},
        expiresAt: new Date(Date.now() + DEFAULT_UPLOAD_EXPIRY_SECONDS * 1000),
      };
    } catch (caught) {
      throw this.#translate(caught, "createSignedUpload", input.key);
    }
  }

  /**
   * A presigned GET, for objects that must not be public.
   *
   * Listing media is served from `publicUrl`; this exists for anything that
   * should be reachable only by someone holding the link for a bounded time —
   * host verification documents, when those arrive (A-011).
   */
  async createSignedDownloadUrl(key: string, expiresInSeconds: number): Promise<string> {
    assertSafeKey(key);

    const command = new GetObjectCommand({ Bucket: this.#config.bucket, Key: key });

    try {
      return await this.#sign(this.#getClient(), command, expiresInSeconds);
    } catch (caught) {
      throw this.#translate(caught, "createSignedDownloadUrl", key);
    }
  }

  async put(input: {
    readonly key: string;
    readonly contentType: string;
    readonly bytes: Uint8Array;
  }): Promise<StoredObject> {
    assertSafeKey(input.key);

    const command = new PutObjectCommand({
      Bucket: this.#config.bucket,
      Key: input.key,
      Body: input.bytes,
      ContentType: input.contentType,
    });

    try {
      await this.#getClient().send(command);
    } catch (caught) {
      throw this.#translate(caught, "put", input.key);
    }

    return { key: input.key, url: this.publicUrl(input.key) };
  }

  /**
   * Remove an object.
   *
   * S3 and R2 both treat deleting a missing key as success, and that is left
   * alone: removal is idempotent, and a retry after a partial failure should
   * not error on objects it already removed.
   */
  async remove(key: string): Promise<void> {
    assertSafeKey(key);

    const command = new DeleteObjectCommand({ Bucket: this.#config.bucket, Key: key });

    try {
      await this.#getClient().send(command);
    } catch (caught) {
      throw this.#translate(caught, "remove", key);
    }
  }

  /**
   * The URL a browser loads the object from.
   *
   * Derived rather than stored, so changing bucket or putting a CDN in front is
   * a configuration change instead of a data migration — the same reason the
   * media table has never held a URL.
   *
   * Static assets (seed photography, brand marks) ship in `public/` and are
   * never uploaded to the bucket, so they resolve against the app's origin.
   */
  publicUrl(key: string): string {
    assertSafeKey(key);
    if (isStaticAssetKey(key)) {
      return `/${key}`;
    }
    return `${this.#config.publicBaseUrl.replace(/\/+$/, "")}/${key}`;
  }
}
