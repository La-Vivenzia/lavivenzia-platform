/**
 * Object storage port — experience media, and later invoices and vouchers.
 *
 * Two ways in, deliberately:
 *
 * **Presigned upload** is the production shape. The browser sends bytes
 * straight to S3 and they never transit the app server, which is what keeps a
 * request thread from being held open for the length of someone's upload.
 *
 * **Server-mediated `put`** is the path used while there is no AWS account.
 * Bytes arrive at the app, are validated, and are written by the adapter. It is
 * a real implementation rather than a stub, so the whole media flow — validate,
 * store, record, serve, delete — is exercised end to end today, and swapping in
 * S3 later changes the adapter and nothing above it.
 */

export interface SignedUpload {
  readonly url: string;
  readonly fields: Readonly<Record<string, string>>;
  readonly expiresAt: Date;
}

export interface StoredObject {
  readonly key: string;
  /** Where the stored object can be read from. */
  readonly url: string;
}

export interface StoragePort {
  /** Browsers upload directly to storage; bytes never transit the app server. */
  createSignedUpload(input: {
    readonly key: string;
    readonly contentType: string;
    readonly maxBytes: number;
  }): Promise<SignedUpload>;

  createSignedDownloadUrl(key: string, expiresInSeconds: number): Promise<string>;

  /**
   * Store bytes the server already holds.
   *
   * The key is generated by the caller and is never client-supplied. An
   * implementation must treat it as opaque and must not let it escape its own
   * namespace.
   */
  put(input: {
    readonly key: string;
    readonly contentType: string;
    readonly bytes: Uint8Array;
  }): Promise<StoredObject>;

  /**
   * Remove a stored object.
   *
   * Must be idempotent: deleting something already gone is a success, because
   * the caller is reconciling and would otherwise fail on a retry.
   */
  remove(key: string): Promise<void>;

  /** Public URL for an object, where the bucket or directory serves publicly. */
  publicUrl(key: string): string;
}
